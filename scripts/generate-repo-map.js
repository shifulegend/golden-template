#!/usr/bin/env node
/**
 * generate-repo-map.js
 * Generates docs/ai/repo-map.md — a compact symbol map of the repository.
 * Pattern reference: Aider's repo-map (https://aider.chat/docs/repomap.html)
 *
 * USAGE:
 *   node scripts/generate-repo-map.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const OUTPUT_PATH = path.join(__dirname, '..', 'docs', 'ai', 'repo-map.md');
const IGNORE_DIRS = new Set(['node_modules', '.git', 'dist', 'build', '.next', 'coverage', 'docs']);
const SOURCE_EXT_RE = /\.(js|ts|jsx|tsx|py)$/;
const SYMBOL_RE = /(?:export\s+)?(?:function|class|const|def)\s+([A-Za-z0-9_]+)/g;

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (IGNORE_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, files);
    } else if (SOURCE_EXT_RE.test(entry.name)) {
      files.push(full);
    }
  }
  return files;
}

function extractSymbols(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const symbols = [];
  let match;
  while ((match = SYMBOL_RE.exec(content)) !== null) {
    symbols.push(match[1]);
  }
  SYMBOL_RE.lastIndex = 0;
  return symbols;
}

function generate() {
  const root = path.join(__dirname, '..');
  const files = walk(root).sort();
  const lines = [
    '# Repository Map',
    '<!-- AUTO-GENERATED by scripts/generate-repo-map.js — do not hand-edit -->',
    `<!-- Generated: ${new Date().toISOString()} -->`,
    '',
    'Compact symbol map for instant codebase orientation. See `docs/ai/context-efficiency.md`.',
    '',
  ];
  for (const file of files) {
    const rel = path.relative(root, file);
    const symbols = extractSymbols(file);
    if (symbols.length === 0) continue;
    lines.push(`## ${rel}`);
    for (const sym of symbols) {
      lines.push(`- \`${sym}\``);
    }
    lines.push('');
  }
  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf8');
  console.log(`Repo map written to ${OUTPUT_PATH}`);
}

try {
  generate();
} catch (err) {
  const code = err && err.code ? err.code : 'UNKNOWN_ERROR';
  console.error(`[generate-repo-map] Failed (${code}): ${err.message}`);
  process.exit(1);
}
